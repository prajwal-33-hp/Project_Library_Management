def init_database():
    """Initialize database and insert 500 books."""
    max_attempts = 5
    delay = 2
    
    for attempt in range(1, max_attempts + 1):
        try:
            # Create database if not exists
            cfg = DB_CONFIG.copy()
            cfg.pop('database', None)
            conn = mysql.connector.connect(**cfg)
            cur = conn.cursor()
            cur.execute(f"CREATE DATABASE IF NOT EXISTS {DB_CONFIG['database']}")
            conn.commit()
            conn.close()
            
            # Connect to database
            conn = mysql.connector.connect(**DB_CONFIG)
            cur = conn.cursor()
            
            # Create tables
            cur.execute("""
                CREATE TABLE IF NOT EXISTS students (
                    student_id INT AUTO_INCREMENT PRIMARY KEY,
                    username   VARCHAR(100) UNIQUE NOT NULL,
                    password   VARCHAR(255) NOT NULL
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS staff (
                    staff_id INT AUTO_INCREMENT PRIMARY KEY,
                    username VARCHAR(100) UNIQUE NOT NULL,
                    password VARCHAR(255) NOT NULL
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS books (
                    book_id  INT AUTO_INCREMENT PRIMARY KEY,
                    title    VARCHAR(255) NOT NULL,
                    author   VARCHAR(255) NOT NULL,
                    quantity INT NOT NULL DEFAULT 0
                )
            """)
            conn.commit()
            
            # Check if books already exist
            cur.execute("SELECT COUNT(*) FROM books")
            count = cur.fetchone()[0]
            
            if count == 0:
                print(f"Inserting {len(BOOKS)} books...")
                cur.executemany(
                    "INSERT INTO books (title, author, quantity) VALUES (%s, %s, %s)",
                    BOOKS
                )
                conn.commit()
                print(f"✓ Successfully inserted {len(BOOKS)} books!")
            else:
                print(f"✓ Database already has {count} books. Skipping insertion.")
            
            conn.close()
            print("✓ Database initialization complete!")
            return True
            
        except mysql.connector.Error as e:
            print(f"Attempt {attempt}/{max_attempts} failed: {e}")
            if attempt < max_attempts:
                print(f"Retrying in {delay} seconds...")
                time.sleep(delay)
    
    print("✗ Failed to initialize database after all attempts.")
    return False

if __name__ == '__main__':
    init_database()

